import { useEffect, useState } from "react";
import { Link, useSearchParams } from "react-router-dom";
import { reviewApi } from "../services/review.js";
import Pagination from "../components/Pagination.jsx";
import StatusBadge from "../components/StatusBadge.jsx";
import Tilt3DCard from "../components/Tilt3DCard.jsx";
import { formatDateTime } from "../utils/format.js";
import {
  ShieldAlert,
  Search,
  RotateCcw,
  Eye,
} from "lucide-react";

const STATUSES = ["new", "under_review", "resolved", "dismissed"];
const SEVERITIES = ["low", "medium", "high"];
const TYPES = [
  "Bid Pattern Anomaly",
  "Document Similarity",
  "Participation Anomaly",
  "Contract Modification",
  "Timeline Pattern",
  "Entity Relationship",
  "Geographic Pattern",
  "Data Quality Issue",
];

export default function Risks() {
  const [params, setParams] = useSearchParams();

  const page = Number(params.get("page") || 1);
  const limit = Number(params.get("limit") || 25);
  const severity = params.get("severity") || "";
  const status = params.get("status") || "";
  const type = params.get("type") || "";
  const search = params.get("search") || "";

  const [rows, setRows] = useState([]);
  const [summary, setSummary] = useState(null);
  const [pagination, setPagination] = useState({ page: 1, limit, total: 0, totalPages: 1 });
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  const [searchInput, setSearchInput] = useState(search);

  const updateParams = (patch) => {
    const next = new URLSearchParams(params);
    for (const [k, v] of Object.entries(patch)) {
      if (v === undefined || v === null || v === "") next.delete(k);
      else next.set(k, String(v));
    }
    setParams(next, { replace: true });
  };

  useEffect(() => setSearchInput(search), [search]);

  useEffect(() => {
    let cancelled = false;
    setLoading(true);
    setError("");

    const reqs = [
      reviewApi.list({
        page,
        limit,
        severity: severity || undefined,
        status: status || undefined,
        type: type || undefined,
        search: search || undefined,
      }),
      reviewApi.summary(),
    ];
    Promise.all(reqs)
      .then(([listRes, sumRes]) => {
        if (cancelled) return;
        setRows(listRes.data.data || []);
        setPagination(listRes.data.pagination || { page: 1, limit, total: 0, totalPages: 1 });
        setSummary(sumRes.data.data || null);
      })
      .catch((err) => {
        if (!cancelled) setError(err?.response?.data?.error?.message || "Failed to load indicators");
      })
      .finally(() => !cancelled && setLoading(false));

    return () => {
      cancelled = true;
    };
  }, [page, limit, severity, status, type, search]);

  return (
    <div>
      <div className="tl-page-header">
        <div>
          <div
            style={{
              display: "inline-flex",
              alignItems: "center",
              gap: 6,
              fontSize: 11,
              fontFamily: "var(--tl-font-mono)",
              color: "#f87171",
              fontWeight: 700,
              textTransform: "uppercase",
              letterSpacing: 1,
              marginBottom: 4,
            }}
          >
            <ShieldAlert size={14} />
            <span>AI RISK SURVEILLANCE &amp; ANOMALY TRIAGE</span>
          </div>
          <h1 className="tl-page-title">Executive Risk Center</h1>
          <p className="tl-page-sub">
            Forensic review indicators generated by autonomous heuristics and neural collusion models.
          </p>
        </div>
      </div>

      {summary && (
        <div className="tl-grid tl-grid-cols-4" style={{ marginBottom: 24 }}>
          <Tilt3DCard>
            <div style={{ fontSize: 10.5, textTransform: "uppercase", letterSpacing: 0.8, color: "var(--tl-text-muted)", fontWeight: 700 }}>
              Total Flags
            </div>
            <div style={{ fontSize: 28, fontWeight: 800, marginTop: 6, color: "var(--tl-text-primary)" }}>
              {summary.total ?? 0}
            </div>
          </Tilt3DCard>
          <Tilt3DCard>
            <div style={{ fontSize: 10.5, textTransform: "uppercase", letterSpacing: 0.8, color: "#f87171", fontWeight: 700 }}>
              High Severity
            </div>
            <div style={{ fontSize: 28, fontWeight: 800, marginTop: 6, color: "#f87171" }}>
              {summary.high ?? 0}
            </div>
          </Tilt3DCard>
          <Tilt3DCard>
            <div style={{ fontSize: 10.5, textTransform: "uppercase", letterSpacing: 0.8, color: "#fbbf24", fontWeight: 700 }}>
              Medium Severity
            </div>
            <div style={{ fontSize: 28, fontWeight: 800, marginTop: 6, color: "#fbbf24" }}>
              {summary.medium ?? 0}
            </div>
          </Tilt3DCard>
          <Tilt3DCard>
            <div style={{ fontSize: 10.5, textTransform: "uppercase", letterSpacing: 0.8, color: "#60a5fa", fontWeight: 700 }}>
              Low Severity
            </div>
            <div style={{ fontSize: 28, fontWeight: 800, marginTop: 6, color: "#60a5fa" }}>
              {summary.low ?? 0}
            </div>
          </Tilt3DCard>
          <Tilt3DCard>
            <div style={{ fontSize: 10.5, textTransform: "uppercase", letterSpacing: 0.8, color: "var(--tl-text-dim)", fontWeight: 700 }}>
              New / Unreviewed
            </div>
            <div style={{ fontSize: 24, fontWeight: 700, marginTop: 6, color: "var(--tl-text-primary)" }}>
              {summary.new ?? 0}
            </div>
          </Tilt3DCard>
          <Tilt3DCard>
            <div style={{ fontSize: 10.5, textTransform: "uppercase", letterSpacing: 0.8, color: "#38bdf8", fontWeight: 700 }}>
              Under Active Review
            </div>
            <div style={{ fontSize: 24, fontWeight: 700, marginTop: 6, color: "#38bdf8" }}>
              {summary.under_review ?? 0}
            </div>
          </Tilt3DCard>
          <Tilt3DCard>
            <div style={{ fontSize: 10.5, textTransform: "uppercase", letterSpacing: 0.8, color: "#34d399", fontWeight: 700 }}>
              Resolved
            </div>
            <div style={{ fontSize: 24, fontWeight: 700, marginTop: 6, color: "#34d399" }}>
              {summary.resolved ?? 0}
            </div>
          </Tilt3DCard>
          <Tilt3DCard>
            <div style={{ fontSize: 10.5, textTransform: "uppercase", letterSpacing: 0.8, color: "var(--tl-text-dim)", fontWeight: 700 }}>
              Dismissed
            </div>
            <div style={{ fontSize: 24, fontWeight: 700, marginTop: 6, color: "var(--tl-text-muted)" }}>
              {summary.dismissed ?? 0}
            </div>
          </Tilt3DCard>
        </div>
      )}

      {/* Filter HUD */}
      <form
        className="tl-filters"
        onSubmit={(e) => {
          e.preventDefault();
          updateParams({ search: searchInput.trim() || undefined, page: 1 });
        }}
      >
        <div style={{ position: "relative", minWidth: 260 }}>
          <input
            type="search"
            placeholder="Search indicator, tender code, contractor…"
            value={searchInput}
            onChange={(e) => setSearchInput(e.target.value)}
            style={{ width: "100%", paddingLeft: 34 }}
          />
          <Search
            size={15}
            style={{
              position: "absolute",
              left: 11,
              top: "50%",
              transform: "translateY(-50%)",
              color: "var(--tl-text-muted)",
              pointerEvents: "none",
            }}
          />
        </div>

        <select
          value={severity}
          onChange={(e) => updateParams({ severity: e.target.value, page: 1 })}
        >
          <option value="">All severities</option>
          {SEVERITIES.map((s) => (
            <option key={s} value={s}>
              {s.toUpperCase()}
            </option>
          ))}
        </select>

        <select
          value={status}
          onChange={(e) => updateParams({ status: e.target.value, page: 1 })}
        >
          <option value="">All review states</option>
          {STATUSES.map((s) => (
            <option key={s} value={s}>
              {s.replace("_", " ").toUpperCase()}
            </option>
          ))}
        </select>

        <select value={type} onChange={(e) => updateParams({ type: e.target.value, page: 1 })}>
          <option value="">All anomaly types</option>
          {TYPES.map((t) => (
            <option key={t} value={t}>
              {t}
            </option>
          ))}
        </select>

        <button type="submit" className="tl-btn" style={{ gap: 6 }}>
          <Search size={14} />
          <span>Filter</span>
        </button>

        <button
          type="button"
          className="tl-btn-ghost"
          style={{ gap: 6 }}
          onClick={() => {
            setSearchInput("");
            setParams(new URLSearchParams(), { replace: true });
          }}
        >
          <RotateCcw size={14} />
          <span>Reset</span>
        </button>
      </form>

      {error && <div className="tl-error-bar">{error}</div>}

      <div className="tl-table-wrap">
        <table className="tl-table">
          <thead>
            <tr>
              <th>Severity</th>
              <th>Anomaly Category</th>
              <th>Indicator Title</th>
              <th>Target Tender</th>
              <th>Contractor Entity</th>
              <th>Triage Status</th>
              <th>Detected</th>
              <th>Notes</th>
              <th>Actions</th>
            </tr>
          </thead>
          <tbody>
            {loading ? (
              <tr>
                <td colSpan={9}>
                  <div className="tl-loading">Evaluating risk indicators…</div>
                </td>
              </tr>
            ) : rows.length === 0 ? (
              <tr>
                <td colSpan={9}>
                  <div className="tl-empty">No indicators match active surveillance filters.</div>
                </td>
              </tr>
            ) : (
              rows.map((r) => (
                <tr key={r.id}>
                  <td>
                    <StatusBadge status={r.severity} />
                  </td>
                  <td style={{ fontSize: 12.5, color: "var(--tl-text-secondary)" }}>{r.type}</td>
                  <td style={{ maxWidth: 320, whiteSpace: "normal", fontWeight: 600 }}>
                    {r.title}
                  </td>
                  <td>
                    {r.tenderCode ? (
                      <Link
                        to={`/tenders/${r.tenderId}`}
                        style={{ fontFamily: "var(--tl-font-mono)", color: "#38bdf8" }}
                      >
                        {r.tenderCode}
                      </Link>
                    ) : (
                      "—"
                    )}
                  </td>
                  <td>{r.companyName || "—"}</td>
                  <td>
                    <span
                      style={{
                        padding: "2px 8px",
                        borderRadius: 6,
                        background: "rgba(255, 255, 255, 0.05)",
                        border: "1px solid var(--tl-glass-border)",
                        fontSize: 11,
                        textTransform: "capitalize",
                        fontWeight: 600,
                      }}
                    >
                      {r.status?.replace("_", " ")}
                    </span>
                  </td>
                  <td style={{ fontSize: 12, color: "var(--tl-text-muted)" }}>
                    {formatDateTime(r.createdAt)}
                  </td>
                  <td style={{ fontFamily: "var(--tl-font-mono)", fontSize: 12 }}>
                    {r.noteCount ?? 0}
                  </td>
                  <td>
                    <Link
                      to={`/risks/${r.id}`}
                      className="tl-btn-ghost"
                      style={{
                        padding: "4px 10px",
                        fontSize: 12,
                        display: "inline-flex",
                        alignItems: "center",
                        gap: 4,
                      }}
                    >
                      <Eye size={13} />
                      <span>Investigate</span>
                    </Link>
                  </td>
                </tr>
              ))
            )}
          </tbody>
        </table>
      </div>

      <Pagination
        page={pagination.page}
        totalPages={pagination.totalPages}
        total={pagination.total}
        limit={pagination.limit}
        onChange={(p) => updateParams({ page: p })}
      />
    </div>
  );
}
